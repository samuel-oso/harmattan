// Builds lib/land.ts: a one-degree grid marking which cells of the map are African land.
// Source: Natural Earth 1:110m countries (public domain), https://www.naturalearthdata.com/
// Run: node scripts/land.mjs [path-to-countries.geojson]
import { readFile, writeFile } from "node:fs/promises";

const SOURCE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson";
const BOX = { west: -20, east: 54, north: 39, south: -37 };
const COLS = BOX.east - BOX.west;
const ROWS = BOX.north - BOX.south;

async function load(path) {
  if (path) return JSON.parse(await readFile(path, "utf8"));
  const res = await fetch(SOURCE, { signal: AbortSignal.timeout(30_000) });
  if (!res.ok) throw new Error(`Natural Earth download failed: ${res.status}`);
  return res.json();
}

function inRing(ring, x, y) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

const inPolygon = ([outer, ...holes], x, y) => inRing(outer, x, y) && !holes.some((hole) => inRing(hole, x, y));

const world = await load(process.argv[2]);
const polygons = world.features
  .filter((f) => f.properties.CONTINENT === "Africa")
  .flatMap((f) => (f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates));

let count = 0;
const rows = [];
for (let r = 0; r < ROWS; r++) {
  let bits = "";
  for (let c = 0; c < COLS; c++) {
    const land = polygons.some((p) => inPolygon(p, BOX.west + c + 0.5, BOX.north - r - 0.5));
    if (land) count++;
    bits += land ? "1" : "0";
  }
  // four cells to a hex digit
  rows.push(bits.padEnd(Math.ceil(COLS / 4) * 4, "0").replace(/.{4}/g, (n) => parseInt(n, 2).toString(16)));
}

const out = `// Generated by scripts/land.mjs from Natural Earth (public domain). Do not edit by hand.
export const BOX = ${JSON.stringify(BOX)};
export const COLS = ${COLS};
export const ROWS = ${ROWS};

// one string per row from north to south; each hex digit is four cells from west to east, 1 for land
const LAND = [
${rows.map((r) => `  "${r}",`).join("\n")}
];

// the [column, row] of every land cell
export function landCells(): [number, number][] {
  const cells: [number, number][] = [];
  LAND.forEach((row, r) => {
    for (let c = 0; c < COLS; c++) if ((parseInt(row[c >> 2], 16) >> (3 - (c & 3))) & 1) cells.push([c, r]);
  });
  return cells;
}

// a place on the map as fractions of its width and height
export function project(lon: number, lat: number): { x: number; y: number } {
  return { x: (lon - BOX.west) / COLS, y: (BOX.north - lat) / ROWS };
}
`;
await writeFile(new URL("../lib/land.ts", import.meta.url), out);
console.log(`${count} land cells of ${COLS * ROWS}`);
